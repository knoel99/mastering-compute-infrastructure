"""Generate the SLO burn-rate rules AND their promtool tests from one model (course module 14, lab 14.2).

SLO: SLO_TARGET of the jobs start within THRESHOLD_S seconds of submission, over a 30-day period.
Alerts follow the multiwindow, multi-burn-rate recipe of the Google SRE Workbook (chapter "Alerting on SLOs"):
    error_ratio(long window) > burn * (1 - SLO)  AND  error_ratio(short window) > burn * (1 - SLO)
with a short window 1/12 of the long one. The firing minutes used by the tests are COMPUTED by simulating the
same windows on the same synthetic counters, so the thresholds in the YAML cannot drift from the model.

    python3 gen_rules.py            write rules/slo.rules.yml and tests/slo.rules.test.yml
    python3 gen_rules.py --check    fail if the committed files differ from what the model generates
    python3 gen_rules.py --table    print the burn-rate table (budget share consumed, time to fire)
"""
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
SLO_TARGET = 0.95
THRESHOLD_S = 600
PERIOD_H = 30 * 24
# (alert, severity, long window, short window, burn rate); window lengths in minutes
ALERTS = [
    ("JobWaitSLOFastBurn", "page", "1h", "5m", 14.4),
    ("JobWaitSLOSlowBurn", "page", "6h", "30m", 6.0),
    ("JobWaitSLOTicket", "ticket", "3d", "6h", 1.0),
]
MINUTES = {"5m": 5, "30m": 30, "1h": 60, "6h": 360, "3d": 4320}
BAD = f"slo:slurm_job_wait_seconds_over_{THRESHOLD_S}:error_ratio_rate"
PER_MIN = 20           # jobs started per minute in the synthetic traffic
LONG_HISTORY = 4400    # healthy minutes before the incident when the 3-day window matters (3 d = 4320 min)
SHORT_HISTORY = 400    # enough for the 6 h window (360 min); the 3-day ticket is not asserted in those scenarios
TOTAL_MIN = 6200       # simulation horizon; the emitted series are cut just after the last checked minute
START = 1000           # counters start away from zero so that rate() has no zero-crossing effect


def budget_share(burn, window):
    """Fraction of the period's error budget consumed if the burn rate holds for the whole long window."""
    return burn * (MINUTES[window] / 60) / PERIOD_H


def threshold(burn):
    return round(burn * (1 - SLO_TARGET), 6)


def rules_yaml():
    rec = [{"record": f"{BAD}{w}",
            "expr": f'1 - (sum(rate(slurm_job_wait_seconds_bucket{{le="{THRESHOLD_S}.0"}}[{w}])) '
                    f"/ sum(rate(slurm_job_wait_seconds_count[{w}])))"}
           for w in ("5m", "30m", "1h", "6h", "3d")]
    alerts = []
    for name, sev, lw, sw, burn in ALERTS:
        t = threshold(burn)
        alerts.append({
            "alert": name,
            "expr": f"{BAD}{lw} > {t} and {BAD}{sw} > {t}",
            "labels": {"severity": sev, "slo": "burn"},
            "annotations": {
                "summary": f"queue-wait SLO burning at {burn}x or more (windows {lw} and {sw}); "
                           f"{budget_share(burn, lw):.0%} of the 30-day budget per {lw}",
                "runbook_url": f"runbooks/{name}.md"}})
    doc = {"groups": [{"name": "slo-recording", "interval": "1m", "rules": rec},
                      {"name": "slo-alerts", "interval": "1m", "rules": alerts}]}
    head = (f"# GENERATED by gen_rules.py: do not edit. SLO {SLO_TARGET:.1%} of jobs start within {THRESHOLD_S} s, 30-day period.\n"
            "# Alerts carry no `for:` on purpose: the two windows already filter blips (SRE Workbook, ch. 5).\n")
    return head + yaml.safe_dump(doc, sort_keys=False, width=200)


# ------------------------------------------------------------------------------------------ simulation
def counters(incidents):
    """incidents: list of (start_min, end_min, error_fraction). Returns cumulative (good, total) per minute."""
    good, total, g, t = [], [], START, START
    for m in range(TOTAL_MIN + 1):
        good.append(g)
        total.append(t)
        err = next((e for s, en, e in incidents if s <= m < en), 0.0)
        g += round(PER_MIN * (1 - err))
        t += PER_MIN
    return good, total


def error_ratio(good, total, m, window):
    w = MINUTES[window]
    if m < w:
        return 0.0
    return 1 - (good[m] - good[m - w]) / (total[m] - total[m - w])


def firing(good, total, alert, m):
    _, _, lw, sw, burn = next(a for a in ALERTS if a[0] == alert)
    t = threshold(burn)
    return error_ratio(good, total, m, lw) > t and error_ratio(good, total, m, sw) > t


def first(pred, lo, hi):
    return next((m for m in range(lo, hi) if pred(m)), None)


def series_values(cum):
    """Run-length encode a cumulative counter with promtool's `a+bxn` notation."""
    segs, i = [], 0
    while i < len(cum):
        step = cum[i + 1] - cum[i] if i + 1 < len(cum) else 0
        j = i
        while j + 1 < len(cum) and cum[j + 1] - cum[j] == step:
            j += 1
        segs.append(f"{cum[i]}+{step}x{j - i}")
        i = j + 1
    return " ".join(segs)


def scenario(name, incidents, expectations):
    good, total = counters(incidents)
    checks = expectations(good, total)
    end = max(m for m, _, _ in checks) + 5
    good, total = good[:end + 1], total[:end + 1]
    lab = 'slurm_job_wait_seconds_%s{qos="normal"%s}'
    t = {
        "interval": "1m",
        "input_series": [
            {"series": lab % ("count", ""), "values": series_values(total)},
            {"series": lab % ("bucket", f',le="{THRESHOLD_S}.0"'), "values": series_values(good)},
        ],
        "alert_rule_test": [],
    }
    for minute, alert, should_fire in checks:
        t["alert_rule_test"].append({
            "eval_time": f"{minute}m", "alertname": alert,
            "exp_alerts": [{"exp_labels": {"severity": dict((a[0], a[1]) for a in ALERTS)[alert], "slo": "burn"},
                            "exp_annotations": {"summary": next(r for g in yaml.safe_load(rules_yaml())["groups"]
                                                                for r in g["rules"] if r.get("alert") == alert)["annotations"]["summary"],
                                                "runbook_url": f"runbooks/{alert}.md"}}] if should_fire else []})
    t["name"] = name
    return t


def tests_yaml():
    tests = []
    fast, slow, tick = (a[0] for a in ALERTS)

    H = SHORT_HISTORY

    def outage(good, total):  # 100 % errors for 2 h: fast burn must fire, then reset within minutes
        f = first(lambda m: firing(good, total, fast, m), H, TOTAL_MIN)
        c = first(lambda m: not firing(good, total, fast, m), f, TOTAL_MIN)
        return [(f - 3, fast, False), (f + 3, fast, True), (c - 2, fast, True), (c + 2, fast, False),
                (H + 20, slow, False)]

    tests.append(scenario("total outage for 2 h: page fast, and reset quickly", [(H, H + 120, 1.0)], outage))

    def blip(good, total):  # 10 minutes of 100 % errors: nothing may fire, at any time
        return [(m, a, False) for m in (H + 15, H + 60, H + 300) for a in (fast, slow)]

    tests.append(scenario("10-minute blip: silent", [(H, H + 10, 1.0)], blip))

    def degraded(good, total):  # 40 % errors for 8 h: slow burn pages, fast burn does not
        f = first(lambda m: firing(good, total, slow, m), H, TOTAL_MIN)
        assert first(lambda m: firing(good, total, fast, m), H, TOTAL_MIN) is None
        return [(f - 3, slow, False), (f + 3, slow, True), (f + 3, fast, False)]

    tests.append(scenario("40 % errors for 8 h: slow burn only", [(H, H + 480, 0.4)], degraded))

    def creeping(good, total):  # 20 % errors for 30 h: only the ticket fires (3-day window)
        L = LONG_HISTORY
        f = first(lambda m: firing(good, total, tick, m), L, TOTAL_MIN)
        assert first(lambda m: firing(good, total, slow, m), L, TOTAL_MIN) is None
        return [(f - 3, tick, False), (f + 3, tick, True), (f + 3, slow, False)]

    tests.append(scenario("20 % errors for 30 h: ticket only", [(LONG_HISTORY, LONG_HISTORY + 1800, 0.2)], creeping))
    doc = {"rule_files": ["../rules/slo.rules.yml"], "evaluation_interval": "1m", "tests": tests}
    return ("# GENERATED by gen_rules.py: do not edit. Eval times come from simulating the same windows.\n"
            + yaml.safe_dump(doc, sort_keys=False, width=250))


def table():
    print(f"SLO {SLO_TARGET:.1%} within {THRESHOLD_S} s, budget fraction {1 - SLO_TARGET:.1%} over {PERIOD_H // 24} days")
    print(f"{'alert':<20}{'burn':>6}{'long':>6}{'short':>7}{'error ratio >':>15}{'budget/long window':>20}{'time to fire at 100 % errors':>32}")
    for name, sev, lw, sw, burn in ALERTS:
        t = threshold(burn)
        print(f"{name:<20}{burn:>6}{lw:>6}{sw:>7}{t:>15}{budget_share(burn, lw):>19.1%}{t * MINUTES[lw]:>26.1f} min")


def main(argv):
    files = {HERE / "rules" / "slo.rules.yml": rules_yaml(), HERE / "tests" / "slo.rules.test.yml": tests_yaml()}
    if "--table" in argv:
        table()
        return 0
    if "--check" in argv:
        stale = [str(p.relative_to(HERE)) for p, text in files.items() if not p.exists() or p.read_text() != text]
        print("generated files up to date" if not stale else f"STALE: {stale}")
        return 1 if stale else 0
    for p, text in files.items():
        p.write_text(text)
        print("wrote", p.relative_to(HERE))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
